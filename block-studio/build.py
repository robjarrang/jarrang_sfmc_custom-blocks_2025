"""Rebuild local export assets and the standalone Studio using Python's standard library."""

import base64
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


def write(path, content):
    (ROOT / path).write_text(content, encoding="utf-8")


def brand_css():
    fonts = []
    for name, weight in [("regular.woff2", "400"), ("medium.woff2", "500")]:
        data = base64.b64encode((ROOT / "vendor" / "brand" / name).read_bytes()).decode()
        fonts.append(
            '@font-face{font-family:"Neue Montreal";font-style:normal;font-weight:'
            + weight
            + ';font-display:swap;src:url(data:font/woff2;base64,'
            + data
            + ') format("woff2")}\n'
        )
    return (
        "/* Generated by build.py from brand-theme.css and bundled fonts. */\n"
        + "".join(fonts)
        + read("src/brand-theme.css")
    )


def css_rules(css):
    rules, depth, start = [], 0, 0
    for i, char in enumerate(css):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                rules.append(css[start : i + 1].strip())
                start = i + 1
    return rules


def runtime_brand_css():
    """Keep brand rules used by the exported editor, without embedded fonts."""
    used = {"editor", "runtime-brand", "jarrang-wordmark", "standalone", "status"}
    for name in ["controls.js", "rich-editor.js", "runtime.js", "runtime.css", "controls.css"]:
        used.update(re.findall(r"[a-z][a-z0-9_-]*", read("src/" + name)))

    def wanted(selector):
        return all(token in used for token in re.findall(r"[.#]([a-z][a-z0-9_-]*)", selector))

    def filtered(rule):
        head, body = rule.split("{", 1)
        if head.startswith("@media"):
            inner = [r for r in map(filtered, css_rules(body.rsplit("}", 1)[0])) if r]
            return head + "{\n" + "\n".join(inner) + "\n}" if inner else ""
        selectors = [s.strip() for s in head.split(",") if wanted(s)]
        return ", ".join(selectors) + "{" + body if selectors else ""

    theme = re.sub(r"/\*.*?\*/", "", read("src/brand-theme.css"), flags=re.S)
    css = "\n".join(r for r in map(filtered, css_rules(theme)) if r)
    return (
        "/* Generated by build.py from brand-theme.css: only what exported SFMC editors use, with system fonts. */\n"
        + css.replace("'Neue Montreal', ", "")
        + "\n"
    )


def minify_css(css):
    """Strip comments/whitespace from our controlled stylesheets, not arbitrary CSS."""
    assert "url(" not in css
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    return re.sub(r" ?([{};,]) ?", r"\1", css).replace(";}", "}").strip() + "\n"


def js_bundle(rich):
    """One runtime request; rich-text controls are included only in the rich variant."""
    parts = ["vendor/blocksdk.js", "src/logic.js", "src/runtime-core.js"]
    if rich:
        parts.append("src/rich-editor.js")
    parts.extend(["src/controls.js", "src/runtime.js"])
    return (
        "/* Generated by build.py: Salesforce Block SDK (BSD-3-Clause, see BLOCKSDK-LICENSE.txt), logic, runtime-core, "
        + ("rich-editor, " if rich else "")
        + "controls and runtime. */\n"
        + "\n;\n".join(read(p) for p in parts)
    )


def standalone_html():
    html = read("index.html")
    for css in ["studio.css", "controls.css", "brand.css", "code-editor.css"]:
        # Accept readable, formatted HTML as well as the earlier compact entry point.
        pattern = r'<link\s+rel="stylesheet"\s+href="src/' + re.escape(css) + r'"\s*/?>'
        html, count = re.subn(pattern, lambda _: "<style>" + read("src/" + css) + "</style>", html)
        if count != 1:
            raise ValueError("Expected one stylesheet reference for " + css)

    def inline_script(match):
        code = re.sub(r"</script", r"<\\/script", read(match[1]), flags=re.I)
        return "<script>" + code + "</script>"

    return re.sub(r'<script\s+src="([^"]+)"\s*>\s*</script>', inline_script, html)


def build():
    write("src/brand.css", brand_css())
    write("src/runtime-brand.css", runtime_brand_css())
    assets = {
        "runtime.bundle.js": js_bundle(False),
        "runtime.rich.bundle.js": js_bundle(True),
        "runtime.bundle.css": (
            "/* Generated by build.py: runtime, controls and runtime-brand styles. */\n"
            + minify_css("".join(read("src/" + name) for name in [
                "runtime.css", "controls.css", "runtime-brand.css"
            ]))
        ),
        "brand.css": read("src/brand.css"),
        "BLOCKSDK-LICENSE.txt": read("vendor/BLOCKSDK-LICENSE.txt"),
    }
    version = hashlib.sha256(json.dumps(assets, sort_keys=True).encode()).hexdigest()[:16]
    write("src/export-assets.js", (
        "/* Generated by build.py. Local export dependencies. */\n"
        + "window.EXPORT_ASSET_VERSION = " + json.dumps(version) + ";\n"
        + "window.EXPORT_ASSETS = " + json.dumps(assets, ensure_ascii=True) + ";\n"
    ))
    # Embed editable snapshots for offline use. Never overwrite existing browser drafts.
    projects = [
        json.loads(p.read_text(encoding="utf-8"))
        for p in sorted((REPO_ROOT / "projects").glob("*/*.jarrang.json"))
    ]
    write("src/repository-projects.js", (
        "/* Generated by build.py from projects/. Browser drafts are never overwritten automatically. */\n"
        + "window.REPOSITORY_PROJECTS = " + json.dumps({"projects": projects}, ensure_ascii=True) + ";\n"
    ))
    html = standalone_html()
    write("Open-Block-Studio.html", html)
    site = REPO_ROOT / "docs" / "studio"
    site.mkdir(parents=True, exist_ok=True)
    (site / "index.html").write_text(html, encoding="utf-8")
    (REPO_ROOT / "docs" / ".nojekyll").write_text("", encoding="utf-8")
    print("Built export assets, Open-Block-Studio.html and docs/studio/index.html")


if __name__ == "__main__":
    build()
